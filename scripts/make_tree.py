"""
Write docs/TREE.md: every source file of Syntra with one line on what it does,
taken from the file itself (a Python module's docstring, the first comment of a
JS/JSX file). Run it after adding, moving or renaming a file:

    python scripts/make_tree.py

A file with no description shows "(no description)": give it one at its top.
"""
from __future__ import annotations

import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SECTIONS = [
    ("backend/app", "Engine (FastAPI, Python)", (".py",)),
    ("frontend/src", "Interface (React + Leaflet)", (".js", ".jsx", ".css")),
    ("scripts", "Scripts", (".py", ".ps1")),
]
SKIP = {"__pycache__", "node_modules", "dist"}


def describe(p: Path) -> str:
    text = p.read_text(encoding="utf-8", errors="ignore")
    if p.suffix == ".py":
        try:
            doc = ast.get_docstring(ast.parse(text)) or ""
        except SyntaxError:
            doc = ""
        para = []
        for l in doc.splitlines():
            if not l.strip():
                if para:
                    break
                continue
            para.append(l.strip())
        line = " ".join(para)
    elif p.suffix == ".css":
        m = re.search(r"/\*\s*(.+?)(?:\*/|\n)", text)
        line = m.group(1).strip() if m else ""
    elif p.suffix == ".ps1":
        m = re.search(r"^#\s*(.+)$", text, re.M)
        line = m.group(1).strip() if m else ""
    else:
        para = []
        for l in text.splitlines()[:60]:
            s = l.strip()
            if s.startswith(("//", "/**", "* ", "*")) and not s.startswith("*/"):
                t = s.lstrip("/*").strip()
                if t:
                    para.append(t)
                elif para:
                    break
            elif para:
                break
        line = " ".join(para)
    m = re.match(r"(.+?[.;])(\s|$)", line)        # the first sentence
    line = (m.group(1) if m else line).rstrip(".:;").replace(" — ", ": ")
    return (line[:110] + "…") if len(line) > 111 else (line or "(no description)")


def main() -> None:
    out = ["# Code tree", "",
           "Every source file and what it does, read from the file itself. Generated by",
           "`python scripts/make_tree.py`; do not edit by hand. The layers and data flow are",
           "in [ARCHITECTURE.md](ARCHITECTURE.md).", ""]
    for base, title, exts in SECTIONS:
        out += [f"## {title}: `{base}/`", ""]
        rows = []
        for p in sorted((ROOT / base).rglob("*")):
            if p.is_file() and p.suffix in exts and not (SKIP & set(p.parts)) and p.name != "__init__.py":
                rows.append((p.relative_to(ROOT / base).as_posix(), describe(p)))
        current = None
        for rel, d in rows:
            folder = rel.rsplit("/", 1)[0] if "/" in rel else "."
            if folder != current:
                current = folder
                out += ["", f"**{folder}/**" if folder != "." else "**(top)**", "", "| File | What it does |", "| --- | --- |"]
            out.append(f"| `{rel.rsplit('/', 1)[-1]}` | {d.replace('|', '/')} |")
        out.append("")
    (ROOT / "docs" / "TREE.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"docs/TREE.md: {sum(1 for l in out if l.startswith('| `'))} files")


if __name__ == "__main__":
    main()
