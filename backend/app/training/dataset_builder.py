"""
YOLO dataset builder: tiles a (very large) orthomosaic window-by-window,
converts georeferenced annotations into YOLO labels (detect or OBB),
filters black / no-data tiles, samples background tiles, splits
train/val, and applies rotation/flip augmentation.

Ported from the GeoSyntra AI QGIS plugin's core/dataset_builder.py — that
module had no QGIS dependency at all ("annotations arrive already converted
to pixel space"), so the tiling/labelling/augmentation logic here is the
same algorithm, unchanged. Only the raster reader (app.training.raster_window
instead of GDAL/osgeo) and the module paths changed.

`reader` only needs to satisfy a small duck-typed interface (see
app.training.raster_window.RasterReader): `.width`, `.height`, `.count`,
`.dtype`, `.path`, `read_window(xoff, yoff, w, h)`, `black_ratio(rgb, valid)`,
`tile_geotransform(xoff, yoff)`. This keeps DatasetBuilder importable and
unit-testable with a fake in-memory reader, with no rasterio dependency.

`annotations`: list of dicts {"cls": int, "pts": np.ndarray (Nx2) in the
raster's PIXEL coordinate space}. Converting drawn map geometry (lon/lat) to
pixel space is the caller's job (see app/api/training.py).
"""
from __future__ import annotations

import csv
import json
import os
import shutil
import time

import numpy as np

from .augment import DEFAULT_VARIANTS, augment_image, augment_points
from .geometry import clip_polygon_rect, min_area_rect, polygon_area, simplify_rdp, tile_starts, tiles_for_bbox

# a clipped object is also kept when it covers this fraction of the tile, so
# objects larger than a tile (fields, centre pivots, big buildings) are labelled
LARGE_OBJECT_TILE_FRACTION = 0.08


class Cancelled(Exception):
    pass


def _noop(*_a, **_k):
    return False


def write_data_yaml(path: str, root: str, class_names: list[str], task: str) -> None:
    lines = [
        "# YOLO dataset generated by Syntra AI",
        "path: %s" % json.dumps(root.replace("\\", "/")),
        "train: images/train",
        "val: images/val",
        "task: %s" % task,
        "nc: %d" % len(class_names),
        "names:",
    ]
    lines += ["  %d: %s" % (i, json.dumps(n, ensure_ascii=False)) for i, n in enumerate(class_names)]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


class DatasetBuilder:
    def __init__(self, reader, annotations, class_names, out_dir,
                 tile=640, overlap=64, val_split=0.2, neg_ratio=0.1,
                 black_thr=0.8, augment=True, variants=None, augment_val=False,
                 task="detect", min_visibility=0.4, img_fmt="jpg", seed=42,
                 write_world=True, tile_filter=None, area_bounds=None,
                 progress=None, canceled=None, log=None):
        self.r = reader
        self.anns = annotations
        self.names = list(class_names)
        self.out = os.path.abspath(out_dir)
        self.T = int(tile)
        self.O = int(overlap)
        self.val_split = float(val_split)
        self.neg_ratio = float(neg_ratio)
        self.black_thr = float(black_thr)
        self.variants = (variants or DEFAULT_VARIANTS) if augment else ["orig"]
        if "orig" not in self.variants:
            self.variants = ["orig"] + list(self.variants)
        self.augment_val = augment_val
        self.task = task
        self.min_vis = float(min_visibility)
        self.fmt = img_fmt
        self.rng = np.random.default_rng(seed)
        self.write_world = write_world
        self.tile_filter = tile_filter        # callable(xoff, yoff) -> None | bool mask | bool
        self.area_bounds = area_bounds        # (px0, py0, px1, py1) pixel bbox of the area
        self.progress = progress or (lambda p, m=None: None)
        self.canceled = canceled or _noop
        self.log = log or (lambda m: None)
        self.prefix = os.path.splitext(os.path.basename(reader.path))[0].replace(" ", "_")
        self.stats = {"train_images": 0, "val_images": 0, "train_objects": 0,
                      "val_objects": 0, "background_tiles": 0,
                      "rejected_black": 0, "rejected_no_label": 0,
                      "rejected_outside_area": 0,
                      "class_counts": {n: 0 for n in self.names}}
        self.index_rows = []

    # --------------------------------------------------------------- setup
    def _prepare_dirs(self):
        for sub in ("images", "labels"):
            p = os.path.join(self.out, sub)
            if os.path.isdir(p):
                shutil.rmtree(p)
        for split in ("train", "val"):
            os.makedirs(os.path.join(self.out, "images", split), exist_ok=True)
            os.makedirs(os.path.join(self.out, "labels", split), exist_ok=True)

    def _index_annotations(self):
        tiles = {}
        for k, a in enumerate(self.anns):
            p = a["pts"]
            xmin, ymin = p.min(0)
            xmax, ymax = p.max(0)
            a["area"] = polygon_area(p)
            if a["area"] <= 0:
                continue
            for i in tiles_for_bbox(self.xs, self.T, xmin, xmax):
                for j in tiles_for_bbox(self.ys, self.T, ymin, ymax):
                    tiles.setdefault((j, i), []).append(k)
        return tiles

    # -------------------------------------------------------------- labels
    def _tile_labels(self, xoff, yoff, ann_ids):
        T = float(self.T)
        out = []
        for k in ann_ids:
            a = self.anns[k]
            local = a["pts"] - np.array([xoff, yoff], dtype=float)
            clipped = clip_polygon_rect(local, 0, 0, T, T)
            if len(clipped) < 3:
                continue
            c_area = polygon_area(clipped)
            vis = c_area / a["area"]
            if vis < self.min_vis and c_area < LARGE_OBJECT_TILE_FRACTION * T * T:
                continue
            if self.task == "segment":
                corners = simplify_rdp(clipped, 0.6)        # sub-pixel accurate outline
                if len(corners) > 400:
                    corners = simplify_rdp(clipped, 1.5)
            elif self.task == "obb":
                corners = min_area_rect(clipped)
            else:
                mn, mx = clipped.min(0), clipped.max(0)
                corners = np.array([[mn[0], mn[1]], [mx[0], mn[1]], [mx[0], mx[1]], [mn[0], mx[1]]])
            corners = np.clip(corners / T, 0.0, 1.0)
            span = corners.max(0) - corners.min(0)
            if span.min() * T < 1.0:     # degenerate (<1 px)
                continue
            out.append((a["cls"], corners))
        return out

    def _format(self, labels):
        lines = []
        for cls, c in labels:
            if self.task in ("obb", "segment"):
                lines.append("%d " % cls + " ".join("%.6f" % v for v in c.reshape(-1)))
            else:
                mn, mx = c.min(0), c.max(0)
                cx, cy = (mn + mx) / 2.0
                w, h = mx - mn
                lines.append("%d %.6f %.6f %.6f %.6f" % (cls, cx, cy, w, h))
        return "\n".join(lines) + ("\n" if lines else "")

    MIN_AREA_FRACTION = 0.35

    def _area_mask(self, xoff, yoff):
        """None = whole tile usable, False = reject, array = usable pixels."""
        if not self.tile_filter:
            return None
        m = self.tile_filter(xoff, yoff)
        if m is None or m is True:
            return None
        if m is False:
            return False
        if m.mean() < self.MIN_AREA_FRACTION:
            return False
        return m

    # --------------------------------------------------------------- write
    def _fill_empty_val(self):
        """Ultralytics cannot train without validation images. When the planned
        validation tiles were all rejected (or the dataset is very small), copy
        some ORIGINAL (non-augmented) training tiles into val so training always
        works. The metrics are then optimistic — a clear warning is logged."""
        rows = [r for r in self.index_rows if r[1] == "train" and r[2] == "orig"]
        if not rows:
            rows = [r for r in self.index_rows if r[1] == "train"]
        rows = [r for r in rows if r[5] > 0] or rows          # prefer tiles with objects
        n = max(1, int(round(len(rows) * (self.val_split or 0.2))))
        if len(rows) <= n:
            picked = rows
        else:
            picked = [rows[k] for k in sorted(self.rng.choice(len(rows), size=n, replace=False).tolist())]
        for r in picked:
            stem = os.path.splitext(r[0])[0]
            for sub, ext in (("images", os.path.splitext(r[0])[1]), ("labels", ".txt")):
                src = os.path.join(self.out, sub, "train", stem + ext)
                if os.path.exists(src):
                    shutil.copy2(src, os.path.join(self.out, sub, "val", stem + ext))
            for wext in (".jgw", ".pgw", ".tfw", ".wld"):
                w = os.path.join(self.out, "images", "train", stem + wext)
                if os.path.exists(w):
                    shutil.copy2(w, os.path.join(self.out, "images", "val", stem + wext))
            self.stats["val_images"] += 1
            self.stats["val_objects"] += int(r[5])
            self.index_rows.append([r[0], "val", "copy-of-train", r[3], r[4], r[5], r[6]])
        self.log("WARNING: no tile was left for validation (too few annotated tiles). %d training tile(s) were "
                 "copied to the validation set so training can run — the validation scores will be "
                 "optimistic. Annotate more objects (or a larger area) for a real validation."
                 % len(picked))

    def _write_tile(self, rgb, labels, split, name, xoff, yoff, br):
        from .raster_window import write_image

        variants = self.variants if (split == "train" or self.augment_val) else ["orig"]
        for v in variants:
            img = augment_image(rgb, v)
            lab = [(c, augment_points(p, v)) for c, p in labels]
            stem = "%s_%s" % (name, v)
            ip = os.path.join(self.out, "images", split, "%s.%s" % (stem, self.fmt))
            gt = self.r.tile_geotransform(xoff, yoff) if (v == "orig" and self.write_world) else None
            write_image(ip, img, self.fmt, geotransform=gt,
                       wkt=self.r.wkt if gt else None)
            with open(os.path.join(self.out, "labels", split, stem + ".txt"), "w") as fh:
                fh.write(self._format(lab))
            self.stats["%s_images" % split] += 1
            self.stats["%s_objects" % split] += len(lab)
            for c, _ in lab:
                self.stats["class_counts"][self.names[c]] += 1
            self.index_rows.append([stem + "." + self.fmt, split, v, int(xoff), int(yoff),
                                    len(lab), round(br, 4)])

    # ----------------------------------------------------------------- run
    def run(self):
        t0 = time.time()
        r = self.r
        self.xs = tile_starts(r.width, self.T, self.O)
        self.ys = tile_starts(r.height, self.T, self.O)
        n_grid = len(self.xs) * len(self.ys)
        self.log("Raster %d x %d px, %d bands (%s) -> %d x %d = %d candidate tiles"
                 % (r.width, r.height, r.count, r.dtype, len(self.xs), len(self.ys), n_grid))
        self._prepare_dirs()

        tile_map = self._index_annotations()
        pos_keys = list(tile_map.keys())
        self.rng.shuffle(pos_keys)
        n_val = int(round(len(pos_keys) * self.val_split))
        if self.val_split > 0 and n_val == 0 and len(pos_keys) >= 2:
            n_val = 1
        val_set = set(pos_keys[:n_val])
        self.log("%d annotations touch %d tiles (%d planned for validation)"
                 % (len(self.anns), len(pos_keys), n_val))

        # ---------------- positive tiles
        n_pos = 0
        for c, key in enumerate(sorted(pos_keys)):
            if self.canceled():
                raise Cancelled()
            j, i = key
            xoff, yoff = int(self.xs[i]), int(self.ys[j])
            amask = self._area_mask(xoff, yoff)
            if amask is False:
                self.stats["rejected_outside_area"] += 1
                continue
            labels = self._tile_labels(xoff, yoff, tile_map[key])
            if not labels:
                self.stats["rejected_no_label"] += 1
                continue
            rgb, valid = r.read_window(xoff, yoff, self.T, self.T)
            if amask is not None:
                rgb[~amask] = 0          # outside the annotated area: masked (never seen as background)
                valid &= amask
            br = r.black_ratio(rgb, valid)
            if br > self.black_thr:
                self.stats["rejected_black"] += 1
                continue
            split = "val" if key in val_set else "train"
            self._write_tile(rgb, labels, split, "%s_r%05d_c%05d" % (self.prefix, j, i),
                             xoff, yoff, br)
            n_pos += 1
            self.progress(70.0 * (c + 1) / max(len(pos_keys), 1),
                          None if c % 25 else "Positive tiles: %d/%d" % (c + 1, len(pos_keys)))

        # ---------------- background tiles
        n_neg_target = int(round(n_pos * self.neg_ratio))
        n_neg, attempts = 0, 0
        occupied = set(tile_map.keys())
        ix0, ix1, iy0, iy1 = 0, len(self.xs), 0, len(self.ys)
        if self.area_bounds is not None:
            px0, py0, px1, py1 = self.area_bounds
            ix0 = int(np.searchsorted(self.xs, px0, side="left"))
            ix1 = int(np.searchsorted(self.xs, px1 - self.T, side="right"))
            iy0 = int(np.searchsorted(self.ys, py0, side="left"))
            iy1 = int(np.searchsorted(self.ys, py1 - self.T, side="right"))
        n_cand = max(ix1 - ix0, 0) * max(iy1 - iy0, 0)
        free = n_cand - sum(1 for (j, i) in occupied if ix0 <= i < ix1 and iy0 <= j < iy1)
        max_attempts = max(50, n_neg_target * 30)
        if n_neg_target and free > 0:
            self.log("Sampling %d background tiles from %d empty tiles" % (n_neg_target, free))
        tried = set()
        while n_neg < n_neg_target and attempts < max_attempts and len(tried) < free and n_cand > 0:
            if self.canceled():
                raise Cancelled()
            attempts += 1
            j = int(self.rng.integers(iy0, iy1))
            i = int(self.rng.integers(ix0, ix1))
            if (j, i) in occupied or (j, i) in tried:
                continue
            tried.add((j, i))
            xoff, yoff = int(self.xs[i]), int(self.ys[j])
            amask = self._area_mask(xoff, yoff)
            if amask is False:
                continue
            rgb, valid = r.read_window(xoff, yoff, self.T, self.T)
            if amask is not None:
                rgb[~amask] = 0
                valid &= amask
            br = r.black_ratio(rgb, valid)
            if br > self.black_thr:
                self.stats["rejected_black"] += 1
                continue
            split = "val" if self.rng.random() < self.val_split else "train"
            self._write_tile(rgb, [], split, "%s_bg_r%05d_c%05d" % (self.prefix, j, i),
                             xoff, yoff, br)
            n_neg += 1
            self.stats["background_tiles"] += 1
            self.progress(70.0 + 25.0 * n_neg / max(n_neg_target, 1))

        # ---------------- metadata
        if self.stats["val_images"] == 0 and self.stats["train_images"] > 0:
            self._fill_empty_val()
        yaml_path = os.path.join(self.out, "data.yaml")
        write_data_yaml(yaml_path, self.out, self.names, self.task)
        with open(os.path.join(self.out, "classes.txt"), "w", encoding="utf-8") as fh:
            fh.write("\n".join(self.names) + "\n")
        with open(os.path.join(self.out, "tiles_index.csv"), "w", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(["image", "split", "augmentation", "x_offset_px", "y_offset_px",
                        "objects", "black_ratio"])
            w.writerows(self.index_rows)
        info = {
            "created": time.strftime("%Y-%m-%d %H:%M:%S"),
            "source_raster": os.path.abspath(r.path), "raster_size": [r.width, r.height],
            "geotransform": list(getattr(r, "gt", [])), "crs_wkt": getattr(r, "wkt", ""),
            "task": self.task, "tile_size": self.T, "overlap": self.O,
            "val_split": self.val_split, "background_ratio": self.neg_ratio,
            "max_black_ratio": self.black_thr, "augmentations": self.variants,
            "min_visibility": self.min_vis, "classes": self.names,
            "stats": self.stats, "seconds": round(time.time() - t0, 1),
        }
        with open(os.path.join(self.out, "dataset_info.json"), "w", encoding="utf-8") as fh:
            json.dump(info, fh, indent=2, ensure_ascii=False)
        self.progress(100.0, "Done")
        return yaml_path, info
